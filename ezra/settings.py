# Behind a reverse proxy (nginx, Render, Railway...) the client IP is in
# X-Forwarded-For. Only trust that header when a proxy actually sets it.
BEHIND_PROXY = env_bool("BEHIND_PROXY", False)
if BEHIND_PROXY:
    SECURE_PROXY_SSL_HEADER = ("HTTP_X_FORWARDED_PROTO", "https")

# Public POST endpoints: max submissions per client IP per window.
